export function partnerStatus(value: string, language: PartnerLanguage): string {
  const keys: Record<string, keyof typeof en> = { Requested: 'statusRequested', Offered: 'statusOffered', Accepted: 'statusAccepted', InProgress: 'statusInProgress', Completed: 'statusCompleted', Cancelled: 'statusCancelled' };
  return keys[value] ? partnerCopy[language][keys[value]] : (language === 'en' ? value : fi.statusUnknown);
}
